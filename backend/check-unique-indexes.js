const SQL = `
  SELECT c.relname AS table_name,
         idx.indisprimary AS is_pk,
         pg_get_indexdef(idx.indexrelid) AS def
  FROM pg_index idx
  JOIN pg_class c ON c.oid = idx.indrelid
  JOIN pg_class i ON i.oid = idx.indexrelid
  JOIN pg_namespace n ON n.oid = c.relnamespace
  WHERE n.nspname = 'public' AND idx.indisunique
  ORDER BY c.relname, i.relname
`;

// Normalise an index definition down to "table(colA, colB)" so the two
// databases compare on shape, not on autogenerated constraint names.
function key(row) {
  const m = row.def.match(/\(([^)]*)\)\s*$/);
  return `${row.table_name}(${m ? m[1].replace(/\s+/g, ' ').trim() : '?'})`;
}

(async () => {
  try {
    const [l, n] = await Promise.all([local.query(SQL), neon.query(SQL)]);

    const localKeys = new Set(l.rows.map(key));
    const neonKeys = new Set(n.rows.map(key));

    const missing = [...localKeys].filter(k => !neonKeys.has(k)).sort();
    const extra = [...neonKeys].filter(k => !localKeys.has(k)).sort();

    console.log(`local unique indexes: ${localKeys.size}`);
    console.log(`neon  unique indexes: ${neonKeys.size}\n`);

    if (missing.length) {
      console.log(`MISSING ON NEON (${missing.length}):`);
      missing.forEach(k => console.log('  - ' + k));
    } else {
      console.log('Nothing missing on Neon.');
    }

    if (extra.length) {
      console.log(`\nEXTRA ON NEON (${extra.length}):`);
      extra.forEach(k => console.log('  + ' + k));
    }
  } finally {
    await local.end();
    await neon.end();
  }
})().catch(e => { console.error(e.message); process.exit(1); });
